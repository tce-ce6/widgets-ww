//Playing Lotties

function playCorrectAnswerLottie(objectName) {

  const containerId = `${objectName}-${wordIndex}`;
  const container = document.getElementById(containerId);

  if (!container) {
    console.warn(`Container ${containerId} not found`);
    return;
  }

  const variant = (wordIndex % 2 === 0) ? '01' : '02';

  // 3. Construct the path (e.g., "./Assets/JSON/tree_01.json")
  const animationPath = `./Assets/Images/JSON/${objectName}_${variant}.json`;

  // Clear previous SVG if any
  container.innerHTML = '';
  // Make sure the container is visible (some containers may be hidden by default)
  container.style.display = 'block';

  const anim = lottie.loadAnimation({
    container: container,
    renderer: 'svg',
    loop: false,
    autoplay: true,
    path: animationPath,
    rendererSettings: {
      hideOnTransparent: false, // Prevents disappearing if frames are empty
      preserveAspectRatio: 'xMidYMid meet'
    }
  });

  // Force it to stay on the last frame
  anim.addEventListener('complete', () => {
    anim.goToAndStop(anim.totalFrames - 1, true);
  });
}

function resetLotties() {
  // Ensure wordObj exists before trying to extract the image
  if (!wordObj || !wordObj.image) return;

  // 1. Extract the name (e.g., "mountain")
  const objectName = wordObj.image.match(/\/([^/]+)\./)[1];

  const slot = document.getElementById(`${objectName}Word`);
  const wordDiv = document.getElementById(`${objectName}Main`);
  if (slot || wordDiv) {
    slot.textContent = "";
    slot.style.display = "none";
    wordDiv.style.display = "none";
  }

  // 2. Loop through and clear the specific IDs for that object
  // Changed i to start at 0 and go to 5 (adjust if you have more leaves)
  for (let i = 0; i <= 4; i++) {
    const leafId = `${objectName}-${i}`;
    const objectContainer = document.getElementById(leafId);
    if (objectContainer) {
      objectContainer.innerHTML = '';
    }
  }
}

/**
 * DATA LAYER: Manages the words and ensures no repeats
 */
class WordPicker {
  constructor(data) {
    this.data = data;
    this.history = new Set();
    this.allWords = this.flattenData();

    this.images = IMAGES;
    this.imageIndex = 0;
  }

  flattenData() {
    let flatList = [];
    for (const groupKey in this.data) {
      this.data[groupKey].forEach((item, index) => {
        flatList.push({ group: groupKey, root: item.word, details: item });
      });
    }
    return flatList;
  }

  getNext() {
    const available = this.allWords.filter(w => !this.history.has(`${w.group}-${w.root}`));

    if (available.length === 0) {
      this.history.clear();
      return this.getNext();
    }

    const selected = available[Math.floor(Math.random() * available.length)];
    this.history.add(`${selected.group}-${selected.root}`);

    // 🔁 rotate image (1 → 2 → 3 → 4 → 1 ...)
    const image = this.images[this.imageIndex];
    this.imageIndex = (this.imageIndex + 1) % this.images.length;

    return {
      ...selected,
      image
    };
  }
}

function handleSmoothMove(source, target) {
  if (!source || !target) return;
  if (target.dataset.full === "true") return;

  target.dataset.full = "true";
  target.style.display = "block";

  source.style.opacity = "0.3";
  source.style.pointerEvents = "none";
  // source.style.filter = "blur(3px)"; // Permanently disable and blur

  const clone = source.cloneNode(true);
  clone.removeAttribute("id");

  clone.style.position = "absolute";
  clone.style.top = "0";
  clone.style.left = "0";
  clone.style.opacity = "1";
  clone.style.filter = "none"; // Remove blur for the animated piece
  clone.style.pointerEvents = "none";
  clone.style.fontSize = "32px";
  clone.style.fontWeight = "bold";

  target.appendChild(clone);
}

function showExampleSentences(wordObj) {
  const popup = document.getElementById('examplePopup');
  const list = document.getElementById('exampleSentenceList');

  if (!popup || !list) return;

  list.innerHTML = "";

  const sentencesObj = wordObj.details.sentences || {};

  Object.entries(sentencesObj).forEach(([key, sentence]) => {
    const li = document.createElement('li');

    // Create regex to bold the key inside sentence (case-insensitive)
    const regex = new RegExp(`(${key})`, 'gi');

    // Replace key with bold version
    li.innerHTML = sentence.replace(regex, '<strong>$1</strong>');

    list.appendChild(li);
  });

  popup.setAttribute('aria-hidden', 'false');
}

function showAllAnswers(wordObj) {
  if (!wordObj || !wordObj.details || !Array.isArray(wordObj.details.answer)) return;

  const imgEl = document.getElementById('objects-img');

  const answers = wordObj.details.answer;
  const objectName = wordObj.image.match(/\/([^/]+)\./)[1];

  const assetMap = {
    tree: './Assets/tree-1.svg',
    milestone: './Assets/milestone-1.svg',
    mountain: './Assets/mountain-1.svg',
    stone: './Assets/stone-1.svg'
  };

  // If the object exists in our map, update the source
  if (assetMap[objectName]) {
    imgEl.src = assetMap[objectName];
  }
  // 1. Reset standard word slots (word1, word2, etc)
  const wordSlots = [
    document.getElementById('word1'),
    document.getElementById('word2'),
    document.getElementById('word3'),
    document.getElementById('word4'),
    document.getElementById('word5')
  ];

  wordSlots.forEach(slot => {
    if (!slot) return;
    slot.textContent = "";
    slot.style.display = "none";
  });

  // 2. Mapping for the visual group containers
  const mapping = {
    tree: { container: 'treeWords', prefix: 'treeWord' },
    milestone: { container: 'milestoneWords', prefix: 'milestoneWord' },
    mountain: { container: 'mountainWords', prefix: 'mountainWord' },
    stone: { container: 'stoneObjects', prefix: 'stoneWord' }
  };

  const map = mapping[objectName];

  // Show the main group container (e.g., the tree SVG group)
  if (map) {
    const groupEl = document.getElementById(map.container);
    if (groupEl) groupEl.style.display = 'block';
  }

  // 3. Fill slots and visual elements based on answers
  answers.forEach((answer, index) => {
    const cleanAnswer = answer.trim();

    // Update standard list slots
    if (wordSlots[index]) {
      wordSlots[index].textContent = cleanAnswer;
      wordSlots[index].style.display = "block";
    }

    // Update visual group slots (foreignObjects)
    if (map) {
      const slotId = `${map.prefix}${index + 1}`;
      const fo = document.getElementById(slotId);
      if (fo) {
        fo.style.display = 'block';
        const span = fo.querySelector('span');
        if (span) span.textContent = cleanAnswer;
      }

      // Show associated lottie/leaf containers if they exist
      const lottieContainer = document.getElementById(`${objectName}-${index}`);
      if (lottieContainer) lottieContainer.style.display = 'block';
    }
  });

  // 4. Disable suffix interaction since answers are revealed
  document.querySelectorAll("#list-suffix li").forEach(li => {
    li.style.pointerEvents = "none";
    li.style.opacity = "0.3";
  });

  // Show the example button as the round is effectively over
  if (typeof showExample !== 'undefined') {
    showExample.style.display = 'block';
  }
}



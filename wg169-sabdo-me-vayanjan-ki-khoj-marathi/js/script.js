function playSound(letter) {
  const soundFile = soundJson[letter];

  if (!soundFile) {
    console.warn("No sound for:", letter);
    return;
  }
  if (currentAudio) {
    currentAudio.pause();
    currentAudio.currentTime = 0;
  }

  currentAudio = new Audio(`./assets/audio/vyanjan/${soundFile}`);
  currentAudio.play();
}


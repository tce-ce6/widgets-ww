// --- UI wiring ---
let currentStanzaIndex = 0;
let greenMarker = document.getElementById('green-marker');
let yellowMarker = document.getElementById('yellow-marker');
let blueMarker = document.getElementById('blue-marker');
let pinkMarker = document.getElementById('pink-marker');

function renderStanza(index) {
  const stanzaObj = STANZAS[index % STANZAS.length];
  if (!stanzaObj) return;

  const [line1 = '', line2 = '', line3 = '', line4 = ''] = stanzaObj.stanza || [];
  const author = stanzaObj.source || 'Unknown author';

  const s1 = document.getElementById('S1');
  const s2 = document.getElementById('S2');
  const s3 = document.getElementById('S3');
  const s4 = document.getElementById('S4');
  const authorEl = document.getElementById('author');
  

  if (s1) s1.textContent = line1;
  if (s2) s2.textContent = line2;
  if (s3) s3.textContent = line3;
  if (s4) s4.textContent = line4;
  if (authorEl) authorEl.textContent = `- ${author}`;
}

function nextStanza() {
  currentStanzaIndex = (currentStanzaIndex + 1) % STANZAS.length;
  renderStanza(currentStanzaIndex);
}

document.addEventListener('DOMContentLoaded', function () {

  greenMarker.addEventListener('click', () => {
    console.log('green');
    document.body.style.cursor = "url('Assets/Images/Final images/Green_Highlighter.svg'), auto";
  });

  yellowMarker.addEventListener('click', () => {
    console.log('yellow');
    document.body.style.cursor = "url('Assets/Images/Final images/Yellow_Highlighter.svg'), auto";
  })

  blueMarker.addEventListener('click', () => {
    console.log('blue');
    document.body.style.cursor = "url('Assets/Images/Final images/Blue_Highlighter.svg'), auto";
  })

  pinkMarker.addEventListener('click', () => {
    console.log('pink');
    document.body.style.cursor = "url('Assets/Images/Final images/Pink_Highlighter.svg'), auto";
  })
  // initial render
  renderStanza(currentStanzaIndex);

  // wire Next button
  const nextBtn = document.getElementById('next-btn');
  if (nextBtn) {
    nextBtn.addEventListener('click', nextStanza);
  }
});